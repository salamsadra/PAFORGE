function outputFile = pa_bridge_run_patbox(exchangeFile, simFixtureMat, algorithm, outputFile)
%PA_BRIDGE_RUN_PATBOX Explicitly gated adapter to the original PATBox code.
% Requirements: a trusted PATBox SIM fixture constructed for this acquisition,
% bearing an exact ID and detector coordinates. The bridge NEVER invents k-Wave
% grids, sensor masks, hardware response, or channel mapping.
arguments
    exchangeFile (1,1) string
    simFixtureMat (1,1) string
    algorithm (1,1) string
    outputFile (1,1) string
end
assert(exist('patReconstruct', 'file') == 2, 'PAHybrid:PATBox', ...
    'Add the original PATBox folder to the MATLAB search path first');
acq = pahybrid.read_acquisition(exchangeFile);
s = load(simFixtureMat, 'sim');
assert(isfield(s, 'sim'), 'PAHybrid:Fixture', 'MAT fixture must contain sim');
sim = s.sim;
fields = {'sensor_data','sensor','kgrid','sound_speed', ...
          'bridge_acquisition_id','bridge_detector_positions_m', ...
          'bridge_coordinate_frame'};
assert(all(isfield(sim, fields)), 'PAHybrid:Fixture', ...
    'Fixture must include PATBox fields plus explicit bridge geometry metadata');
assert(strcmp(char(string(sim.bridge_acquisition_id)), ...
              char(string(acq.metadata.acquisition_id))), ...
    'PAHybrid:Provenance', 'Acquisition ID mismatch between fixture and exchange');
assert(strcmp(char(string(sim.bridge_coordinate_frame)), ...
              char(string(acq.metadata.coordinate_frame))), ...
    'PAHybrid:Frame', 'Coordinate frame mismatch');
fixtureTraces = pa_pr04_extract_traces(sim);
assert(isequal(size(fixtureTraces), size(acq.signals)), ...
    'PAHybrid:ChannelOrder', 'Fixture signal layout differs from incoming acquisition');
% Reference benchmarking must never substitute unrelated waveforms.
assert(isfield(sim,'bridge_validation_mode') && ...
       strcmp(char(string(sim.bridge_validation_mode)),'reference'), ...
    'PAHybrid:Mode', 'Only strictly verified reference mode is allowed in PR-03');
assert(isequal(fixtureTraces,double(acq.signals)), ...
    'PAHybrid:Waveform', 'Fixture traces differ from HDF5; refusing silent signal substitution');
assert(isequal(size(sim.bridge_detector_positions_m), size(acq.detectors_m)) && ...
       all(abs(double(sim.bridge_detector_positions_m(:)) - acq.detectors_m(:)) <= 1e-10), ...
    'PAHybrid:Geometry', 'Detector coordinates/order mismatch; no auto projection');
assert(isprop(sim.kgrid, 'dt') && isfinite(sim.kgrid.dt) && ...
       abs(double(sim.kgrid.dt) - acq.sample_interval_s) <= max(1e-14,1e-6*acq.sample_interval_s), ...
       'PAHybrid:Clock', 'k-Wave grid time step mismatch');
% Reference mode guarantees exact original waveforms (no replacement).
[p0, ~] = patReconstruct(sim, 'Algorithm', char(algorithm), 'SaveOutput', false);
if isfield(sim,'bridge_image_grid')
    grid = sim.bridge_image_grid;
else
    grid = struct();
end
pahybrid.write_result(outputFile, p0, algorithm, ...
                      string(acq.metadata.acquisition_id), sim.kgrid, grid);
end
