"""OPTIONAL conditional variational autoencoder of 2D vessel masks.

Training from experimental data requires segmentation ground-truth. Raw PACT
signals alone do not supply supervised anatomy masks. No clinical weights are
bundled or implied. The demo dataset is procedural, not experimental.
"""
from pathlib import Path
import numpy as np

ANATOMIES=("forearm","skin","breast","carotid","vascular")


def _torch():
    try:import torch
    except ImportError as exc:raise ImportError("Install optional 'torch' for cVAE training") from exc
    return torch


def build_network(latent=24):
    torch=_torch()
    import torch.nn as nn
    import torch.nn.functional as F

    class VesselCVAE(nn.Module):
        def __init__(self):
            super().__init__()
            self.encoder=nn.Sequential(nn.Conv2d(6,16,4,2,1),nn.GELU(),
                nn.Conv2d(16,32,4,2,1),nn.GELU(),nn.Conv2d(32,64,4,2,1),nn.GELU(),
                nn.Conv2d(64,96,4,2,1),nn.GELU())
            self.mu=nn.Linear(96*4*4,latent)
            self.logvar=nn.Linear(96*4*4,latent)
            self.decoder_fc=nn.Linear(latent+5,96*4*4)
            self.decoder=nn.Sequential(nn.ConvTranspose2d(96,64,4,2,1),nn.GELU(),
                nn.ConvTranspose2d(64,32,4,2,1),nn.GELU(),
                nn.ConvTranspose2d(32,16,4,2,1),nn.GELU(),nn.ConvTranspose2d(16,1,4,2,1))
        def decode(self,z,labels):
            hot=F.one_hot(labels,5).to(dtype=z.dtype)
            x=self.decoder_fc(torch.cat([z,hot],dim=1)).reshape(-1,96,4,4)
            return self.decoder(x)
        def forward(self,masks,labels):
            hot=F.one_hot(labels,5).to(dtype=masks.dtype)[:,:,None,None].expand(-1,-1,64,64)
            f=self.encoder(torch.cat([masks,hot],dim=1)).flatten(1)
            mu=self.mu(f);logvar=self.logvar(f).clamp(-12,12)
            z=mu+torch.randn_like(mu)*torch.exp(.5*logvar)
            return self.decode(z,labels),mu,logvar
    return VesselCVAE()


def train_cvae(dataset_path,weights_path,epochs=5,batch_size=16,seed=42,lr=1e-3):
    torch=_torch()
    import torch.nn.functional as F
    from torch.utils.data import DataLoader,TensorDataset
    np.random.seed(seed);torch.manual_seed(seed)
    with np.load(dataset_path,allow_pickle=False) as d:
        masks=np.asarray(d["masks"],dtype=np.float32)
        labels=np.asarray(d["anatomy_idx"],dtype=np.int64)
    if masks.ndim!=3 or masks.shape[1:]!=(64,64) or labels.shape!=(len(masks),):
        raise ValueError("Training file requires masks [N,64,64] and anatomy_idx [N]")
    if not (np.all((labels>=0)&(labels<5)) and np.isfinite(masks).all()):
        raise ValueError("Invalid label or mask")
    masks=np.clip(masks,0,1)
    loader=DataLoader(TensorDataset(torch.tensor(masks[:,None,:,:]),torch.tensor(labels)),
                      batch_size=batch_size,shuffle=True)
    model=build_network();optim=torch.optim.Adam(model.parameters(),lr=lr)
    history=[]
    for ep in range(epochs):
        losses=[]
        for x,l in loader:
            optim.zero_grad();logits,mu,logvar=model(x,l)
            bce=F.binary_cross_entropy_with_logits(logits,x,pos_weight=torch.tensor(6.))
            kl=-.5*(1+logvar-mu.square()-logvar.exp()).sum(dim=1).mean()
            loss=bce+1e-3*kl
            loss.backward();optim.step();losses.append(float(loss.detach()))
        history.append(float(np.mean(losses)))
    Path(weights_path).parent.mkdir(parents=True,exist_ok=True)
    torch.save({"state_dict":model.state_dict(),"latent":24,"anatomies":ANATOMIES,
                "source_dataset":str(dataset_path),"trained_epochs":epochs},weights_path)
    return history


def create_procedural_training_set(path,n=32,seed=42):
    """Smoke-test only: creates synthetic masks, not real experimental labels."""
    from .config import preset
    from .anatomy import generate_tissue
    from scipy.ndimage import zoom
    rng=np.random.default_rng(seed)
    masks=[];labels=[]
    for i in range(n):
        k=i%5;cfg=preset(ANATOMIES[k]).model_copy(update={"grid_size":64})
        tissue=generate_tissue(cfg,rng)
        masks.append(tissue.vessel_mask.astype(np.float32));labels.append(k)
    Path(path).parent.mkdir(exist_ok=True,parents=True)
    np.savez_compressed(path,masks=np.stack(masks),anatomy_idx=np.array(labels))
    return path


def sample_vessel_prior(config,rng):
    torch=_torch()
    from scipy.ndimage import zoom
    # Only load weights generated by this project and trusted locally.
    saved=torch.load(config.generator_weights,map_location="cpu",weights_only=True)
    model=build_network(saved["latent"])
    model.load_state_dict(saved["state_dict"]);model.eval()
    latent=rng.normal(size=(1,saved["latent"])).astype(np.float32)
    label=torch.tensor([ANATOMIES.index(config.anatomy)])
    with torch.no_grad():
        mask=torch.sigmoid(model.decode(torch.tensor(latent),label))[0,0].cpu().numpy()
    # Sparse vessel masks can collapse to an empty mask before convergence.
    # Adaptive quantile sampling supplies a demonstrative sparse spatial prior;
    # it DOES NOT validate learned human vascular anatomy.
    from scipy.ndimage import gaussian_filter
    mask=gaussian_filter(mask,0.9)
    if config.grid_size!=64:
        mask=zoom(mask,config.grid_size/64,order=1)
        mask=mask[:config.grid_size,:config.grid_size]
    return mask
