def _npy(a):
    b=io.BytesIO();np.save(b,a);return b.getvalue()


def _fixture_zip(path,n=6):
    with zipfile.ZipFile(path,'w',compression=zipfile.ZIP_DEFLATED) as z:
        for i in range(n):
            group=f'P.{i}.1';yy,xx=np.mgrid[:32,:32]
            labels=np.zeros((32,32),dtype=np.uint8)
            labels[(xx-16)**2+(yy-16)**2<12**2]=1
            labels[((xx-14-i%3)**2/18+(yy-15)**2/40)<1]=2
            labels[((xx-22)**2+(yy-16+i%2)**2)<12]=3
            z.writestr(f'invision/labels/{group}.npy',_npy(labels))
            for wavelength in (700,750):
                mua=np.choose(labels,[1.,3.,8.,12.]).astype(float)*(1+.1*(wavelength-700)/50)
                musp=np.choose(labels,[10.,20.,30.,40.]).astype(float)
                z.writestr(f'invision/mua/{group}_{wavelength}.npy',_npy(mua))
                z.writestr(f'invision/musp/{group}_{wavelength}.npy',_npy(musp))


def test_prepare_and_train_and_generate(tmp_path):
    archive=tmp_path/'invision.zip';_fixture_zip(archive)
    prepared=prepare_openqpai(archive,tmp_path/'prepared','1/m','1/m',seed=11)
    assert prepared['counts']['groups']==6
    assert prepared['counts']['train']+prepared['counts']['validation']+prepared['counts']['test']==6
    profile=json.loads(Path(prepared['optical_profile']).read_text())
    assert {r['group'] for r in profile['measurements']}<=set(profile['groups']['train'])
    with pytest.raises(ValueError):sample_optics(prepared['optical_profile'],np.ones((10,10),int),810,np.random.default_rng())
    weights=tmp_path/'material.pt'
    report=train(prepared['training_corpus'],prepared['optical_profile'],weights,epochs=2,batch_size=2,seed=1)
    assert len(report['history'])==2 and weights.exists()
    mask=sample(weights,np.random.default_rng(22),64)
    assert mask.shape==(64,64)
    cfg=SimConfig.model_validate({**preset('vascular').model_dump(),
        'anatomy':'material_phantom','anatomy_engine':'material_cvae','generator_weights':str(weights),
        'optical_profile':prepared['optical_profile'],'wavelength_nm':700,
        'grid_size':64,'time_steps':80,'transducers':12,'fov_m':.07,'detector_filter':False,
        'reconstruction_method':'das','samples':1,'seed':27})
    paths=run_batch(cfg,tmp_path/'generated')
    assert (paths[0]/'raw_signals.h5').exists()
    assert (paths[0]/'reconstruction.h5').exists()
    assert (paths[0]/'reconstruction.png').exists()
    with h5py.File(paths[0]/'raw_signals.h5') as f:
        assert f.attrs['synthetic'] and f['raw_data'].shape==(12,80)
    info=json.loads((paths[0]/'manifest.json').read_text())
    assert info['information']['material_provenance']['label_identity'].startswith('phantom material')
    # Empirical mode also generates new samples using a train-only shape.
    cfg2=cfg.model_copy(update={'anatomy_engine':'empirical_material',
                     'generator_weights':prepared['training_corpus']})
    p2=run_batch(cfg2,tmp_path/'empirical')
    assert (p2[0]/'reconstruction.h5').exists()


def test_unit_declaration_and_no_leakage(tmp_path):
    archive=tmp_path/'invision.zip';_fixture_zip(archive)
    with pytest.raises(ValueError,match='explicitly'):
        prepare_openqpai(archive,tmp_path/'bad','unknown','1/cm')
    prepared=prepare_openqpai(archive,tmp_path/'good','1/cm','1/m')
    profile=json.loads(Path(prepared['optical_profile']).read_text())
    assert all(r['absorption_m_inv']>=100 for r in profile['measurements'])
    assert not(set(profile['groups']['train'])&set(profile['groups']['test']))


def test_experimental_fdtd_and_filtered_methods(tmp_path):
    # Test an ideal wave signal generated by the very same solver (inverse crime).
    # Does not attest real-data reconstruction accuracy.
    from paforge.inverse import ForwardOperator
    size=48;fov=.08;dt=1e-7;nt=70
    ang=np.linspace(0,2*np.pi,10,endpoint=False)
    xy=np.column_stack([.020*np.cos(ang),.020*np.sin(ang)])
    pos=np.column_stack([xy,np.zeros(len(xy))])
    px=np.column_stack([xy[:,1]/(fov/size)+(size-1)/2,xy[:,0]/(fov/size)+(size-1)/2])
    op=ForwardOperator(np.full((size,size),1500.),px,fov,dt,nt)
    p0=np.zeros((size,size));p0[21:24,24:27]=1
    traces=op.forward(p0)
    raw=tmp_path/'raw.h5'
    with h5py.File(raw,'w') as f:
        f.create_dataset('raw_data',data=traces)
        f.create_dataset('detector_positions_m',data=pos)
        f.attrs['sampling_rate_hz']=1/dt
        f.attrs['synthetic']=True
    for method in ('ubp','das','filtered_ubp','adjoint_fdtd','fista'):
        image=reconstruct_experimental(raw,tmp_path/method,method,fov,48,1500.,
                 iterations=2,time_decimate=1,filter_low_hz=0.1e6,filter_high_hz=2e6)
        assert image.shape==(48,48)
        assert np.isfinite(image).all()
        assert (tmp_path/method/'experimental_reconstruction.h5').exists()
    with pytest.raises(ValueError,match='increase --fov-m'):
        reconstruct_experimental(raw,tmp_path/'bad','fista',.02,48,1500.,iterations=1,time_decimate=1)


def test_ipasc_planar_coordinate_auto_import(tmp_path):
    src=tmp_path/'ipasc.hdf5'
    with h5py.File(src,'w') as f:
        f.create_dataset('binary_time_series_data',data=np.zeros((6,50,1,1)))
        m=f.create_group('meta_data');m.create_dataset('ad_sampling_rate',data=40e6)
        m.create_dataset('acquisition_wavelengths',data=700)
        det=f.create_group('meta_data_device/detectors')
        for i in range(6):
            g=det.create_group(f'{i:010d}')
            g.create_dataset('detector_position',data=[.005*np.cos(i),0.,.005*np.sin(i)])
    out=normalize_ipasc(src,tmp_path/'normalized.h5','test_import','phantom_test','unknown')
    with h5py.File(out) as f:
        assert f['raw_data'].shape==(6,50)
        assert np.ptp(f['detector_positions_m'][:,2])==0
        assert f.attrs['origin_status']=='unknown'
    with pytest.raises(ValueError,match='Non-planar'):
        with h5py.File(src,'r+') as f:
            for i in range(6):f[f'meta_data_device/detectors/{i:010d}/detector_position'][1]=.01*i
        normalize_ipasc(src,tmp_path/'invalid.h5','test','group','unknown')


