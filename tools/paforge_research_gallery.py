#!/usr/bin/env python3
"""Read-only, provenance-separated PAForge research gallery.

Experimental panels are the PUBLISHERS' OpenQPAIData InVision reconstructions,
labels, optical property arrays, and measured ADC traces. They are NOT PAForge
reconstructions and not calibrated pressure units. For publication, cite
https://doi.org/10.5281/zenodo.14044853 (CC BY 4.0).

Synthetic panels are from PAForge's original HDF5 output, not experimental RF.
Only source-group TRAIN members are eligible, as verified against optical_profile.json.
"""
from __future__ import annotations
import argparse, csv, hashlib, io, json, zipfile
from pathlib import Path
import h5py
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

DEFAULT_GROUPS = ('P.5.8.2', 'P.5.10.2', 'P.5.29')
DEFAULT_WAVELENGTHS = (700, 800)
DATA_DOI = 'https://doi.org/10.5281/zenodo.14044853'

def npy(z, name):
    return np.load(io.BytesIO(z.read(name)), allow_pickle=False)

def load_real(z, gid, wav):
    raw_name = f'invision/raw/{gid}_{wav}_ipasc.hdf5'
    with h5py.File(io.BytesIO(z.read(raw_name)), 'r') as f:
        sig=np.asarray(f['binary_time_series_data'][:, :, 0, 0],dtype=np.float32)
        fs=float(f['meta_data/ad_sampling_rate'][()])
        wave=int(f['meta_data/acquisition_wavelengths'][()])
        if wave != int(wav): raise ValueError(f'Wavelength mismatch in upstream metadata: {raw_name}')
        if sig.shape[0] < 2 or sig.shape[1] < 100 or fs <= 0: raise ValueError(f'Invalid raw shape or rate: {raw_name}')
    return dict(group=gid,wavelength_nm=wav,sampling_rate_hz=fs,raw=sig,
        labels=npy(z,f'invision/labels/{gid}.npy'),
        recon=npy(z,f'invision/recon/{gid}_{wav}.npy'),
        mua=npy(z,f'invision/mua/{gid}_{wav}.npy'),
        musp=npy(z,f'invision/musp/{gid}_{wav}.npy'),source_file=raw_name)

def load_synth(folder):
    p=Path(folder)
    m=json.loads((p/'manifest.json').read_text())
    if not m.get('synthetic',False):raise ValueError('Non-synthetic sample refused')
    with h5py.File(p/'ground_truth.h5') as f:
        label=f['labels'][:];p0=f['initial_pressure_pa'][:]
    with h5py.File(p/'raw_signals.h5') as f:
        raw=f['raw_data'][:]
        time=f['time_s'][:]
    with h5py.File(p/'reconstruction.h5') as f:recon=f['image'][:]
    return dict(folder=p,labels=label,p0=p0,raw=raw,recon=recon,time_s=time,manifest=m)

def imshow(ax,arr,title,cmap='viridis',sym=False):
    if sym:
        vmax=np.percentile(np.abs(arr),99.2)
        ax.imshow(arr,cmap='RdBu_r',vmin=-vmax,vmax=vmax,aspect='auto')
    else:ax.imshow(arr,cmap=cmap,aspect='equal' if arr.shape[0]==arr.shape[1] else 'auto')
    ax.set_title(title,fontsize=9)
    ax.set_xticks([]);ax.set_yticks([])

def make_real_panels(data,out):
    # One row per photon wavelength / phantom. The measured sinogram is plotted
    # after per-channel median subtraction solely as a DISPLAY TRANSFORM.
    n=len(data)
    fig,axes=plt.subplots(n,4,figsize=(15,max(3,n*2.8)),dpi=170,constrained_layout=True)
    axes=np.atleast_2d(axes)
    rows=[]
    for i,d in enumerate(data):
        gid=d['group']; wav=d['wavelength_nm']
        imshow(axes[i,0],d['labels'],f'{gid} | reference material labels',cmap='tab20')
        imshow(axes[i,1],d['mua'],f'{wav} nm | published absorption map',cmap='magma')
        imshow(axes[i,2],d['recon'],f'{wav} nm | PUBLISHED reconstruction',cmap='magma')
        traces=d['raw']-np.median(d['raw'],axis=1,keepdims=True)
        imshow(axes[i,3],traces, f'{wav} nm | MEASURED raw traces (display-centered)',sym=True)
        axes[i,3].set_xlabel('Time sample'); axes[i,3].set_ylabel('Detector')
        rows.append(dict(kind='experimental_source',group_id=gid,wavelength_nm=wav,source=DATA_DOI,
           raw_shape=list(d['raw'].shape),recon_shape=list(d['recon'].shape),
           sampling_rate_hz=d['sampling_rate_hz'],raw_units='unknown ADC counts; not calibrated pressure',
           plot_transform='channelwise median subtraction for display only',
           source_file=d['source_file']))
    fig.suptitle('Original experimental InVision measurements and publisher reconstructions — TRAIN groups only',fontsize=14)
    fig.text(0.5,0.002,'Source: OpenQPAIData, Zenodo 14044853 (CC BY 4.0). PUBLISHED reconstruction; NOT generated by PAForge.',ha='center',fontsize=8)
    fig.savefig(out/'EXP_01_InVision_Original_Train_Groups.png',bbox_inches='tight');plt.close(fig)
    return rows

def make_real_traces(data,out):
    fig,axs=plt.subplots(2,2,figsize=(12,7),dpi=170,constrained_layout=True)
    for r,d in enumerate(data[:2]):
        tr=d['raw']-np.median(d['raw'],axis=1,keepdims=True)
        x=np.arange(tr.shape[1])/d['sampling_rate_hz']*1e6
        ax=axs[r,0]
        for ch in (0,32,64,96,128,160,192,224): ax.plot(x,tr[ch],lw=.75,label=f'ch {ch}')
        ax.set_title(f"{d['group']} | {d['wavelength_nm']} nm | measured ADC traces")
        ax.set_xlabel('Time (µs)');ax.set_ylabel('Display-centered ADC counts')
        if r==0:ax.legend(fontsize=7,ncol=4,frameon=False)
        ax=axs[r,1]
        im=ax.imshow(tr,cmap='RdBu_r',aspect='auto',extent=[x.min(),x.max(),255,0],
                 vmin=-np.percentile(np.abs(tr),99),vmax=np.percentile(np.abs(tr),99))
        ax.set_xlabel('Time (µs)');ax.set_ylabel('Detector index')
        ax.set_title('Measured multi-channel time series (not synthetic)')
    fig.suptitle('OpenQPAIData MSOT InVision — measured raw data, metadata sampling rate',fontsize=13)
    fig.savefig(out/'EXP_02_Measured_RF_Traces.png',bbox_inches='tight');plt.close(fig)

def make_synth_panels(samples,out):
    if not samples:return []
    fig,axes=plt.subplots(len(samples),4,figsize=(14,3.1*len(samples)),dpi=170,constrained_layout=True)
    axes=np.atleast_2d(axes)
    rows=[]
    for i,d in enumerate(samples):
        name=d['folder'].name
        imshow(axes[i,0],d['labels'],f'{name} | generated labels',cmap='tab20')
        imshow(axes[i,1],d['p0'],'Synthetic initial pressure',cmap='magma')
        imshow(axes[i,2],d['recon'],'PAForge UBP-like reconstruction',cmap='magma')
        imshow(axes[i,3],d['raw'],'SYNTHETIC raw traces',sym=True)
        axes[i,3].set_xlabel('Time sample');axes[i,3].set_ylabel('Detector')
        rows.append(dict(kind='synthetic_paforge',name=name,raw_shape=list(d['raw'].shape),
                         p0_shape=list(d['p0'].shape),source='PAForge generated synthetic HDF5',
                         synthetic=True,device_calibrated=False))
    fig.suptitle('PAForge simulated outputs — synthetic data, NOT original experimental measurements',fontsize=13)
    fig.savefig(out/'SIM_01_PAForge_Generated_Examples.png',bbox_inches='tight');plt.close(fig)
    return rows

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--invision-zip',type=Path,required=True,help='Original publisher invision.zip (not the Mac backup tar)')
    ap.add_argument('--optical-profile',type=Path,required=True,help='Original train-group optical_profile.json')
    ap.add_argument('--synthetic-root',type=Path,help='PAForge synthetic output folder containing sample directories')
    ap.add_argument('--out',type=Path,required=True)
    ap.add_argument('--groups',nargs='+',default=list(DEFAULT_GROUPS))
    ap.add_argument('--wavelengths',nargs='+',type=int,default=list(DEFAULT_WAVELENGTHS))
    args=ap.parse_args();args.out.mkdir(parents=True,exist_ok=True)
    profile=json.loads(args.optical_profile.read_text())
    train=set(profile['groups']['train'])
    for gid in args.groups:
        if gid not in train:raise ValueError(f'{gid}: NOT a training group; refusing experimental test/validation viewing')
    data=[]
    with zipfile.ZipFile(args.invision_zip) as z:
        for gid in args.groups:
            for wav in args.wavelengths:
                data.append(load_real(z,gid,wav))
    records=make_real_panels(data,args.out)
    make_real_traces(data,args.out)
    if args.synthetic_root:
        dirs=sorted(p for p in args.synthetic_root.glob('material_phantom_*') if (p/'manifest.json').is_file())
        records.extend(make_synth_panels([load_synth(p) for p in dirs], args.out))
    with (args.out/'figure_index.json').open('w') as f:
        json.dump(dict(source=DATA_DOI,attribution='OpenQPAIData authors / source publisher; dataset CC BY 4.0',
               experimental_rows=sum(x['kind']=='experimental_source' for x in records),
               synthetic_rows=sum(x['kind']=='synthetic_paforge' for x in records),
               evidence=records,warning='Real images are publisher reconstructions; synthetic images are PAForge outputs.'),f,indent=2)
    with (args.out/'data_inventory.csv').open('w',newline='') as f:
        keys=['kind','group_id','wavelength_nm','name','raw_shape','recon_shape','p0_shape','sampling_rate_hz','source','source_file','synthetic','device_calibrated']
        writer=csv.DictWriter(f,fieldnames=keys,extrasaction='ignore');writer.writeheader()
        for r in records:writer.writerow(r)
    print(f'PAFORGE_GALLERY_PASS: {sum(x["kind"]=="experimental_source" for x in records)} measured acquisitions, '
          f'{sum(x["kind"]=="synthetic_paforge" for x in records)} synthetic samples, output={args.out}')

if __name__=='__main__':main()
